import { ProjectInquiryData, InquirySubmissionResult } from '../types';
import { STUDIO_META } from '../data/studioData';

const LOCAL_STORAGE_KEY = 'veltrix_client_inquiries';

export async function submitProjectInquiry(
  data: ProjectInquiryData
): Promise<InquirySubmissionResult> {
  const timestamp = new Date().toISOString();
  const randomSuffix = Math.floor(10000 + Math.random() * 90000);
  const referenceId = `VTX-${randomSuffix}`;

  // 1. Always reliably persist locally in browser storage so the inquiry is never lost
  try {
    const existing = JSON.parse(localStorage.getItem(LOCAL_STORAGE_KEY) || '[]');
    const record = {
      referenceId,
      timestamp,
      data,
    };
    existing.unshift(record);
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(existing.slice(0, 50)));
  } catch (err) {
    console.warn('Could not persist inquiry to localStorage:', err);
  }

  // 2. Attempt delivery to backend API if running
  let backendDelivered = false;
  try {
    const response = await fetch('/api/inquiry', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ referenceId, timestamp, data }),
    });
    if (response.ok) {
      backendDelivered = true;
    }
  } catch {
    // Backend server route is not mandatory; will gracefully fall back to local saved record
    backendDelivered = false;
  }

  return {
    success: true,
    referenceId,
    timestamp,
    message: backendDelivered
      ? 'Your project inquiry has been recorded by our studio backend. We will review your brief within 24-48 hours.'
      : 'Your project brief is saved and registered with Reference ID ' +
        referenceId +
        '. You can also transmit it directly via WhatsApp or copy the summary.',
    data,
  };
}

export function formatWhatsAppMessage(data: ProjectInquiryData, referenceId?: string): string {
  const lines: string[] = [
    `*VELTRIX PROJECT INQUIRY* ${referenceId ? `[Ref: ${referenceId}]` : ''}`,
    `━━━━━━━━━━━━━━━━━━━━`,
    `*Client:* ${data.fullName}${data.brandName ? ` (${data.brandName})` : ''}`,
    `*Email:* ${data.email}`,
    `*Country/Region:* ${data.country || 'Not specified'}`,
    `*Preferred Contact:* ${data.contactMethod}`,
    ``,
    `*Project Services:*`,
    data.projectTypes.length > 0 ? data.projectTypes.map((t) => `• ${t}`).join('\n') : '• Not specified',
    ``,
    `*Goals:*`,
    data.goals.length > 0 ? data.goals.map((g) => `• ${g}`).join('\n') : '• Not specified',
    ``,
    `*Scope & Readiness:*`,
    `• Target Pages: ${data.pageRange || 'Flexible'}`,
    `• Brand/Content Status: ${data.hasBrandingAndContent}`,
    data.existingWebsiteUrl ? `• Existing Website: ${data.existingWebsiteUrl}` : '',
    data.referenceWebsites ? `• References: ${data.referenceWebsites}` : '',
    ``,
    `*Budget & Timeline:*`,
    `• Indicative Budget: ${data.budgetRange || 'To be discussed'}`,
    `• Preferred Timeline: ${data.timeline || 'Flexible'}`,
    ``,
    data.additionalContext ? `*Additional Notes:*\n${data.additionalContext}` : '',
    `━━━━━━━━━━━━━━━━━━━━`,
    `Transmitted via VELTRIX Digital Studio Platform`,
  ].filter(Boolean);

  return encodeURIComponent(lines.join('\n'));
}

export function getWhatsAppUrl(data: ProjectInquiryData, referenceId?: string): string {
  const encoded = formatWhatsAppMessage(data, referenceId);
  return `https://wa.me/${STUDIO_META.whatsappRawNumber}?text=${encoded}`;
}

